import { Effect, Schema } from "effect";
import {
  ArtifactRef,
  Count,
  CreateDocument,
  CreateDraft,
  DraftTransition,
  Execute,
  ImportInto,
  ExportRequest,
  Merge,
  Approve,
  RenderRequest,
  Document,
  Receipt,
  View,
  Digest,
  Id,
  DocumentScope,
} from "@starter/office-contract";
import {
  MergeWitness,
  OriginalActorClaims,
  OwnerClaims,
  NativeReceiptKey,
  NativeReceiptBinding,
} from "@starter/office-server/ports";

export const NativeId = Schema.String.check(Schema.isMinLength(1), Schema.isMaxLength(256));
export const DocumentRow = Schema.Struct({
  owner: OwnerClaims,
  document: Document,
  unitId: NativeId,
  originOperationId: Id,
  location: Schema.Literals(["reserved-main", "main", "draft"]),
});
export const DraftRow = Schema.Struct({
  owner: OwnerClaims,
  id: Id,
  documentId: Id,
  worktreeId: NativeId,
  generation: Count,
  originOperationId: Id,
});
const Intent = Schema.Union([
  Schema.Struct({ kind: Schema.Literal("create"), input: CreateDocument }),
  Schema.Struct({ kind: Schema.Literal("create-draft"), input: CreateDraft }),
  Schema.Struct({ kind: Schema.Literal("execute"), input: Execute }),
  Schema.Struct({ kind: Schema.Literal("import-into"), input: ImportInto }),
  Schema.Struct({ kind: Schema.Literal("render"), input: RenderRequest }),
  Schema.Struct({ kind: Schema.Literal("export"), input: ExportRequest }),
  Schema.Struct({ kind: Schema.Literal("approve"), input: Approve }),
  Schema.Struct({ kind: Schema.Literal("merge"), input: Merge }),
  Schema.Struct({ kind: Schema.Literals(["ready", "reopen", "discard"]), input: DraftTransition }),
]);
export const OperationRow = Schema.Struct({
  owner: OwnerClaims,
  actor: OriginalActorClaims,
  documentId: Id,
  unitId: NativeId,
  worktreeId: Schema.NullOr(NativeId),
  intent: Intent,
  intentDigest: Digest,
  lineageDigest: Digest,
  receipt: Receipt,
  artifacts: Schema.Struct({
    source: Schema.NullOr(ArtifactRef),
    input: Schema.NullOr(ArtifactRef),
    code: Schema.NullOr(ArtifactRef),
    proposal: Schema.NullOr(ArtifactRef),
  }),
  // Rows written before the witness moved into the operation encode without the key.
  merge: Schema.NullOr(MergeWitness).pipe(Schema.withDecodingDefaultKey(Effect.succeed(null))),
  jobId: Schema.NullOr(Id),
  policyVersion: NativeId,
  createdAt: Count,
  updatedAt: Count,
});
export const ReviewRow = Schema.Struct({
  owner: OwnerClaims,
  id: Id,
  documentId: Id,
  unitId: NativeId,
  worktreeId: NativeId,
  generation: Count,
  baselineRevision: Schema.NullOr(Count),
  draftRevision: Count,
  readyRevision: Count,
  mainRevision: Schema.NullOr(Count),
  source: Schema.Literals(["trunk", "worktree"]),
  removed: Schema.Boolean,
  destination: Schema.Struct({ documentId: Id, unitId: NativeId, title: Document.fields.title }),
  main: Schema.NullOr(View),
  baseline: Schema.NullOr(View),
  draft: View,
  result: Schema.NullOr(View),
  preview: Schema.NullOr(ArtifactRef),
  fingerprint: Digest,
  sdkVersion: Schema.Literal("1.0.3"),
  policyVersion: NativeId,
  state: Schema.Literals(["complete", "incomplete", "conflict"]),
  expiresAt: Count,
});
export const ApprovalRow = Schema.Struct({
  owner: OwnerClaims,
  operationId: Id,
  reviewId: Id,
  fingerprint: Digest,
  humanPrincipalId: NativeId,
  sessionEpoch: Count,
  expiresAt: Count,
  consumedBy: Schema.NullOr(Id),
});
export const BarrierRow = Schema.Struct({
  owner: OwnerClaims,
  documentId: Id,
  operationId: Id,
  approvalOperationId: Id,
  reviewId: Id,
  fingerprint: Digest,
  authorityEpoch: Count,
  state: Schema.Literals(["active", "attention"]),
});
export const WriteRow = Schema.Struct({
  id: Id,
  operationId: Id,
  stepId: NativeId,
  receiptKey: NativeReceiptKey,
  preparedReceipt: Schema.NullOr(NativeReceiptBinding),
  documentId: Id,
  unitId: NativeId,
  worktreeId: Schema.NullOr(NativeId),
  nativeType: Schema.Literals([1, 2, 3]),
  generation: Schema.NullOr(Count),
  baseRevision: Schema.NullOr(Count),
  sid: Schema.NullOr(NativeId),
  reqId: Schema.NullOr(Count),
  kind: Schema.Literals(["create-unit", "changeset", "snapshot", "lifecycle"]),
  payload: ArtifactRef,
  phase: Schema.Literals(["staged", "dispatching", "unknown", "confirmed", "absent", "failed"]),
  acceptedRevision: Schema.NullOr(Count),
});
export const Permit = Schema.Struct({
  owner: OwnerClaims,
  documentId: Id,
  operationId: Id,
  stepId: NativeId,
  authorityEpoch: Count,
  serviceEpoch: Count,
  target: Schema.Struct({
    owner: OwnerClaims,
    documentId: Id,
    unitId: NativeId,
    scope: DocumentScope,
  }),
  expectedHead: Schema.NullOr(Count),
  expectedGeneration: Schema.NullOr(Count),
  reviewFingerprint: Schema.NullOr(Digest),
});
