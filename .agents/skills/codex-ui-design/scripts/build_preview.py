"""Build the portable specimen from maintained skill resources; stdlib only."""

from pathlib import Path
import json
import re


def main():
    skill = Path(__file__).resolve().parents[1]
    assets = skill / "assets"
    sources = json.loads((assets / "preview-sources.json").read_text())
    tokens = (assets / "tokens.css").read_text()
    values = dict(re.findall(r"(--[\w-]+)\s*:\s*([^;]+);", tokens))
    recorded = json.loads((assets / "design-tokens.json").read_text())["values"]
    if values != recorded:
        raise ValueError("Update design-tokens.json to match canonical tokens.css")
    styles = tokens + "\n" + "\n".join(
        (assets / path).read_text() for path in sources["styles"]
    )
    regions = [(assets / path).read_text() for path in sources["fragments"]]

    def icon(match):
        name = match.group(1)
        return (assets / "icons" / (name + ".svg")).read_text()

    body = '<div class="shell">' + "\n".join(regions[:4]) + "</div>" + regions[4]
    body = re.sub(r"\{\{icon:([a-z-]+)\}\}", icon, body)
    if "{{icon:" in body:
        raise ValueError("Unresolved icon placeholder")
    behavior = (assets / "playground.js").read_text()
    html = (
        '<!doctype html><html lang="en"><head><meta charset="utf-8">'
        '<meta name="viewport" content="width=device-width,initial-scale=1">'
        '<title>Codex desktop — reconstruction specimen</title>'
        '<!-- Generated by scripts/build_preview.py; edit assets sources. -->'
        '<!-- SVG glyphs: lucide-static 1.53.0, ISC; see ../LUCIDE-LICENSE. -->'
        "<style>" + styles + "</style></head><body>" + body
        + "<script>" + behavior + "</script></body></html>"
    )
    output = assets / "dist" / "components.html"
    output.parent.mkdir(exist_ok=True)
    output.write_text(html)
    print(output)


if __name__ == "__main__":
    main()
